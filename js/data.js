/** Category config: { [catId]: { on: boolean, levels: string[] } } */
export function defaultConfig(levels = LEVELS, cats = CAT_IDS) {
  const cfg = {};
  for (const id of CAT_IDS) cfg[id] = { on: cats.includes(id), levels: [...levels] };
  return cfg;
}

export function normalizeConfig(raw) {
  const cfg = defaultConfig();
  if (raw && typeof raw === 'object') {
    for (const id of CAT_IDS) {
      const e = raw[id];
      if (!e || typeof e !== 'object') continue;
      const lv = Array.isArray(e.levels) ? LEVELS.filter((l) => e.levels.includes(l)) : [...LEVELS];
      cfg[id] = { on: !!e.on, levels: lv.length ? lv : [...LEVELS] };
    }
  }
  if (!CAT_IDS.some((id) => cfg[id].on)) cfg[CAT_IDS[0]].on = true;
  return cfg;
}

export const enabledCats = (cfg) => CAT_IDS.filter((id) => cfg[id]?.on);
